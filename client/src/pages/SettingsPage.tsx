import { Screen } from '../components/common'
import { PACES, useSettings, type Pace } from '../settings'
import { DIFFICULTIES, setFullscreen, type Difficulty } from '../display'
import { NamePacksPanel } from '../components/NamePacks'

export default function SettingsPage() {
  const [s, update] = useSettings()
  return (
    <Screen title="Settings">
      <div className="panel form-grid settings">
        <label>
          Match pace
          <select value={s.pace} onChange={(e) => update({ pace: e.target.value as Pace })}>
            {PACES.map((p) => (
              <option key={p} value={p}>
                {p}
              </option>
            ))}
          </select>
          <small className="muted">
            Fast: no pauses. Normal: the computer thinks, raises its card and turns it over; important cards (team cards, goals,
            penalties, steals, red cards) get a short build-up. Dramatic: a longer build-up. Your own grey cards always turn over at once.
          </small>
        </label>
        <label>
          Difficulty (friendlies)
          <select value={s.difficulty} onChange={(e) => update({ difficulty: e.target.value as Difficulty })}>
            {DIFFICULTIES.map(([d, label]) => (
              <option key={d} value={d}>
                {label}
              </option>
            ))}
          </select>
          <small className="muted">A career keeps the difficulty chosen when it was started.</small>
        </label>
        <label className="checkbox">
          <input type="checkbox" checked={s.autoMiniGames} onChange={(e) => update({ autoMiniGames: e.target.checked })} />
          Decide mini-games automatically (corners, free kicks, Big Chances, penalties)
        </label>
        <h3>Name packs</h3>
        <NamePacksPanel />
        <h3>Sound</h3>
        <label className="checkbox">
          <input type="checkbox" checked={!s.muted} onChange={(e) => update({ muted: !e.target.checked })} />
          Sound on <small className="muted">(press M anywhere to mute / unmute)</small>
        </label>
        {(
          [
            ['volume', 'Master volume'],
            ['sfxVolume', 'Effects'],
            ['crowdVolume', 'Crowd'],
            ['musicVolume', 'Music'],
          ] as const
        ).map(([key, label]) => (
          <label key={key}>
            {label}
            <input type="range" min={0} max={1} step={0.05} value={s[key]} onChange={(e) => update({ [key]: Number(e.target.value) })} />
          </label>
        ))}
        <label className="checkbox">
          <input type="checkbox" checked={s.musicOn} onChange={(e) => update({ musicOn: e.target.checked })} />
          Menu music
        </label>
        <p className="muted small">All sounds and the music are generated by the game itself — no recordings, nothing copyrighted.</p>
        <h3>Display</h3>
        <label className="checkbox">
          <input
            type="checkbox"
            checked={s.fullscreen}
            onChange={(e) => {
              update({ fullscreen: e.target.checked })
              setFullscreen(e.target.checked)
            }}
          />
          Fullscreen <small className="muted">(F11)</small>
        </label>
        <label className="checkbox">
          <input type="checkbox" checked={s.reduceMotion} onChange={(e) => update({ reduceMotion: e.target.checked })} />
          Reduce animations (no confetti or shaking)
        </label>
        <label>
          Manager name
          <input value={s.managerName} onChange={(e) => update({ managerName: e.target.value })} />
        </label>
        <p className="muted small">Settings are stored in your browser.</p>
      </div>
    </Screen>
  )
}
