        ["foul"] = ["Нарушение на {D} — свирка на съдията.", "{D} спира атаката с нарушение."],
        ["free_kick"] = ["Пряк свободен удар за {A} от опасна позиция!"],
        ["free_kick_goal"] = ["Шедьовър от пряк свободен удар! Гол за {A}! {score}"],
