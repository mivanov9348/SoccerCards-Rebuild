        ["kickoff2"] = ["Започва второто полувреме. {A} разиграва от центъра."],
        ["kickoff_after_goal"] = ["{A} подновява играта от центъра."],
        ["halftime"] = ["Свирка за полувремето! {score}"],
        ["fulltime"] = ["Последен съдийски сигнал! Краен резултат: {score}"],

